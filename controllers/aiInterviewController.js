exports.completeInterview = async (req, res) => {
    let client;

    try {
        const studentId = getStudentId(req);

        if (!studentId) {
            return res.status(401).json({
                success: false,
                message: "Unauthorized"
            });
        }

        const { interviewId } = req.body || {};

        if (!interviewId) {
            return res.status(400).json({
                success: false,
                message: "Interview ID is required"
            });
        }

        client = await db.connect();
        await client.query("BEGIN");

        const result = await client.query(
            `SELECT *
             FROM ai_interviews
             WHERE id = $1
             AND student_id = $2
             AND status = 'In Progress'
             FOR UPDATE`,
            [interviewId, studentId]
        );

        if (!result.rows.length) {
            await rollback(client);
            return res.status(404).json({
                success: false,
                message: "Active interview not found"
            });
        }

        const interview = result.rows[0];

        if (interview.pending_question) {
            await rollback(client);
            return res.status(400).json({
                success: false,
                message: "Current question must be answered first"
            });
        }

        const scores = await client.query(
            `SELECT
                COALESCE(
                    ROUND(
                        AVG(
                            (
                                grammar_score +
                                fluency_score +
                                vocabulary_score +
                                relevance_score
                            ) / 4.0
                        )::numeric,
                        2
                    ),
                    0
                ) AS overall_score,
                COUNT(*)::int AS answered
             FROM ai_interview_answers
             WHERE interview_id = $1`,
            [interviewId]
        );

        const data = scores.rows[0];

        if (Number(data.answered) !== Number(interview.total_questions)) {
            await rollback(client);
            return res.status(400).json({
                success: false,
                message: "All questions must be answered first"
            });
        }

        const updated = await client.query(
            `UPDATE ai_interviews
             SET status = 'Completed',
                 overall_score = $1,
                 completed_at = NOW(),
                 pending_question = NULL,
                 pending_question_number = NULL
             WHERE id = $2
             AND student_id = $3
             AND status = 'In Progress'
             RETURNING *`,
            [Number(data.overall_score), interviewId, studentId]
        );

        if (!updated.rows.length) {
            throw new Error("Interview completion failed");
        }

        await client.query("COMMIT");

        return res.json({
            success: true,
            message: "Interview completed successfully",
            report: updated.rows[0]
        });
    } catch (error) {
        await rollback(client);
        console.error("Complete Interview Error:", error);

        return res.status(500).json({
            success: false,
            message: "Unable to complete interview"
        });
    } finally {
        client?.release();
    }
};

