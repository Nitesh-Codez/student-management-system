// GENERATE AI QUESTION
// ======================================================

const generateAIQuestion = async (
    level,
    interviewType,
    questionNumber,
    previousAnswers = []
) => {
    const prompt = `
You are a professional and friendly English interviewer.

Student Level: ${level}
Interview Type: ${interviewType}
Question Number: ${questionNumber}

Previous conversation:
${JSON.stringify(previousAnswers)}

Generate exactly ONE new English interview question.

Rules:
1. Use simple English for beginners.
2. Adapt difficulty to the selected level.
3. Do not repeat previous questions.
4. Keep the question relevant to the interview type.
5. Generate only one question.
6. Do not include numbering or explanations.
7. Return only the question text.
`.trim();

    const rawQuestion = await generateContent(prompt);

    const question = rawQuestion
        .replace(/^["']|["']$/g, "")
        .trim();

    if (!question || question.length > MAX_QUESTION_LENGTH) {
        throw new Error("Invalid question generated by Gemini");
    }

    return question;
};

// ======================================================
// EVALUATE AI ANSWER
// ======================================================

const evaluateAIAnswer = async (question, answer) => {
    const prompt = `
You are a professional English communication teacher.

Evaluate the student's answer.

Question:
${question}

Student Answer:
${answer}

Return valid JSON only in this exact structure:

{
    "grammarScore": 0,
    "fluencyScore": 0,
    "vocabularyScore": 0,
    "relevanceScore": 0,
    "feedback": "Simple feedback",
    "mistakes": [],
    "improvedAnswer": "Corrected answer"
}

Rules:
1. All scores must be numbers between 0 and 100.
2. mistakes must be an array of strings.
3. Use an empty array if there are no mistakes.
4. Evaluate the written transcript, not accent.
5. Do not assume speaking speed from text.
6. Give encouraging and constructive feedback.
7. Do not add Markdown or text outside JSON.
`.trim();

    const rawResponse = await generateContent(prompt);
    const evaluation = extractJsonObject(rawResponse);

    for (const key of SCORE_KEYS) {
        const value = evaluation[key];

        if (
            typeof value !== "number" ||
            !Number.isFinite(value) ||
            value < 0 ||
            value > 100
        ) {
            throw new Error(`Invalid evaluation score: ${key}`);
        }
    }

    if (
        typeof evaluation.feedback !== "string" ||
        !evaluation.feedback.trim()
    ) {
        throw new Error("Invalid evaluation feedback");
    }

    if (
        !Array.isArray(evaluation.mistakes) ||
        !evaluation.mistakes.every((item) => typeof item === "string")
    ) {
        throw new Error("Invalid evaluation mistakes");
    }

    if (
        typeof evaluation.improvedAnswer !== "string" ||
        !evaluation.improvedAnswer.trim()
    ) {
        throw new Error("Invalid improved answer");
    }

    return {
        grammarScore: Math.round(evaluation.grammarScore * 100) / 100,
        fluencyScore: Math.round(evaluation.fluencyScore * 100) / 100,
        vocabularyScore: Math.round(evaluation.vocabularyScore * 100) / 100,
        relevanceScore: Math.round(evaluation.relevanceScore * 100) / 100,
        feedback: evaluation.feedback.trim(),
        mistakes: evaluation.mistakes
            .map((item) => item.trim())
            .filter(Boolean),
        improvedAnswer: evaluation.improvedAnswer.trim()
    };
};

