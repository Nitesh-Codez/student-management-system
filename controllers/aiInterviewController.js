const db = require("../db");
const genAI = require("../config/gemini");
const nodemailer = require("nodemailer");
const crypto = require("crypto");

// ======================================================
// CONSTANTS
// ======================================================

const MODEL_NAME = process.env.GEMINI_MODEL || "gemini-2.5-flash";

const ALLOWED_LEVELS = [
    "Beginner",
    "Intermediate",
    "Advanced"
];

const ALLOWED_INTERVIEW_TYPES = [
    "English AI Interview",
    "Student Viva",
    "General English",
    "Academic Interview",
    "Job Interview"
];

const ALLOWED_QUESTION_COUNTS = [5, 10];

const SCORE_KEYS = [
    "grammarScore",
    "fluencyScore",
    "vocabularyScore",
    "relevanceScore"
];

const MAX_ANSWER_LENGTH = 5000;
const MAX_QUESTION_LENGTH = 1000;

// ======================================================
// COMMON HELPERS
// ======================================================

const rollback = async (client) => {
    if (!client) return;

    try {
        await client.query("ROLLBACK");
    } catch (error) {
        console.error("Rollback Error:", error.message);
    }
};

const getStudentId = (req) => {
    const raw =
        req.user?.id ||
        req.user?.studentId ||
        req.user?.student_id ||
        req.body?.studentId ||
        req.body?.student_id ||
        req.query?.studentId ||
        req.query?.student_id ||
        null;

    if (!raw) return null;
    const parsed = Number(raw);
    return Number.isInteger(parsed) && parsed > 0 ? parsed : String(raw);
};

const isValidText = (value, maxLength = 5000) => {
    return (
        typeof value === "string" &&
        value.trim().length > 0 &&
        value.trim().length <= maxLength
    );
};

const extractJsonObject = (text) => {
    if (typeof text !== "string" || !text.trim()) {
        throw new Error("Empty Gemini response");
    }

    const cleaned = text
        .replace(/```json/gi, "")
        .replace(/```/g, "")
        .trim();

    const start = cleaned.indexOf("{");
    const end = cleaned.lastIndexOf("}");

    if (start === -1 || end <= start) {
        throw new Error("Invalid JSON response from Gemini");
    }

    try {
        return JSON.parse(cleaned.slice(start, end + 1));
    } catch (error) {
        throw new Error("Gemini returned malformed JSON");
    }
};

const generateContent = async (prompt) => {
    if (!genAI?.models?.generateContent) {
        throw new Error("Gemini SDK is not configured correctly");
    }

    const maxRetries = 3;

    for (let attempt = 1; attempt <= maxRetries; attempt++) {
        try {
            const response = await genAI.models.generateContent({
                model: MODEL_NAME,
                contents: prompt
            });

            const text = response?.text;

            if (typeof text !== "string" || !text.trim()) {
                throw new Error("Gemini returned an empty response");
            }

            return text.trim();
        } catch (error) {
            const status = error.status || error.code;
            const retryable =
                status === 503 ||
                status === 429 ||
                status === 500 ||
                status === 502 ||
                status === 504;

            if (!retryable || attempt === maxRetries) {
                throw error;
            }

            const delay = 1000 * Math.pow(2, attempt - 1);
            console.log(
                `Gemini temporary error. Retry ${attempt}/${maxRetries} after ${delay}ms`
            );

            await new Promise((resolve) => setTimeout(resolve, delay));
        }
    }
};

