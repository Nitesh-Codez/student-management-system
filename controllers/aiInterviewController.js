exports.startInterview = async (req, res) => {
    let stage = "initialization";

    try {
        const studentId = getStudentId(req);

        if (!studentId) {
            return res.status(401).json({
                success: false,
                message: "Unauthorized"
            });
        }

        const body = req.body || {};
        const { level, interviewType } = body;
        const totalQuestions = Number(body.totalQuestions ?? 5);

        if (
            !ALLOWED_LEVELS.includes(level) ||
            !ALLOWED_INTERVIEW_TYPES.includes(interviewType) ||
            !ALLOWED_QUESTION_COUNTS.includes(totalQuestions)
        ) {
            return res.status(400).json({
                success: false,
                message: "Invalid interview settings"
            });
        }

        stage = "Gemini question generation";

        const question = await generateAIQuestion(
            level,
            interviewType,
            1,
            []
        );

        stage = "Database INSERT";

        const result = await db.query(
            `INSERT INTO ai_interviews
            (
                student_id,
                level,
                interview_type,
                total_questions,
                status,
                pending_question,
                pending_question_number
            )
            VALUES ($1, $2, $3, $4, 'In Progress', $5, 1)
            RETURNING id`,
            [
                studentId,
                level,
                interviewType,
                totalQuestions,
                question
            ]
        );

        return res.status(201).json({
            success: true,
            interviewId: result.rows[0].id,
            questionNumber: 1,
            question
        });
    } catch (error) {
        console.error("START INTERVIEW FAILED:", {
            stage,
            message: error.message,
            code: error.code
        });

        return res.status(500).json({
            success: false,
            message: "Unable to start interview",
            stage
        });
    }
};

